const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('qw', {
  getState: () => ipcRenderer.invoke('state'),
  refresh: (id) => ipcRenderer.invoke('refresh', id),
  login: (id) => ipcRenderer.invoke('login', id),
  logout: (id) => ipcRenderer.invoke('logout', id),
  openConfig: () => ipcRenderer.invoke('open-config'),
  backupConfig: () => ipcRenderer.invoke('backup-config'),
  exportConfig: () => ipcRenderer.invoke('export-config'),
  importConfig: () => ipcRenderer.invoke('import-config'),
  resetConfig: () => ipcRenderer.invoke('reset-config'),
  checkUpdate: () => ipcRenderer.invoke('check-update'),
  openRelease: () => ipcRenderer.invoke('open-release'),
  setConfig: (patch) => ipcRenderer.invoke('set-config', patch),
  saveCustomProvider: (input) => ipcRenderer.invoke('save-custom-provider', input),
  testCustomProvider: (input) => ipcRenderer.invoke('test-custom-provider', input),
  copyText: (text) => ipcRenderer.invoke('copy-text', text),
  deleteCustomProvider: (id) => ipcRenderer.invoke('delete-custom-provider', id),
  togglePin: () => ipcRenderer.invoke('toggle-pin'),
  setWindowMode: (mode) => ipcRenderer.invoke('set-window-mode', mode),
  hide: () => ipcRenderer.invoke('hide'),
  resize: (h) => ipcRenderer.send('resize', h),
  onState: (cb) => ipcRenderer.on('state', (_e, s) => cb(s)),
});
